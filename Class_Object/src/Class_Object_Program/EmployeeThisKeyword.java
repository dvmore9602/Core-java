package Class_Object_Program;

public class EmployeeThisKeyword {
	int id;
	String name;
	double salary;

	public EmployeeThisKeyword(int id, String name, double salary) {
		
		this.id = id;
		this.name = name;
		this.salary = salary;

	}

	void display() {
		System.out.println(id + "  " + name + " " + salary + " ");

	}



}
