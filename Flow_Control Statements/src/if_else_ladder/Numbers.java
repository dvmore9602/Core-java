package if_else_ladder;

public class Numbers {
	
	public static void main(String[] args) {
		

		        int x = 10;

		        if (x > 20) {
		            System.out.println("A");
		        } 
		        else if (x > 5) {
		            System.out.println("B");
		        } 
		        else if (x > 0) {
		            System.out.println("C");
		        } 
		        else {
		            System.out.println("D");
		        }
		    }
		}
